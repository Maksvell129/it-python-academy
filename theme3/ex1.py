# Запросите у пользователя с клавиатуры две переменные: название статьи расходов
# (строка) и выделенную сумму (должна быть приведена к типу float). Увеличьте эту сумму
# на 15% (инфляционная надбавка) и выведите итоговый результат одной строкой с
# пояснением.

from decimal import Decimal

category = input("Введите категорию расходов: ")
amount  = Decimal(input("Введите потраченную сумму: "))

amount = amount * Decimal("1.15")

print(f"Категория {category} - {amount} к оплате")
