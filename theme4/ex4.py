# Запросите у пользователя текущую температуру воздуха на улице (целое число).
# Напишите цепочку условий: если температура ниже -10, вывести "Холодно, наденьте куртку";
# если от -10 до 15 включительно — "Прохладно, оденьтесь теплее"; если выше 15 — "Тепло, можно идти в футболке".


temp = int(input("Введите температуру: "))

if temp < -10:
    print("Холодно, наденьте куртку")
elif -10 <= temp <= 15:
    print("Прохладно, оденьтесь теплее")
else:
    print("Тепло, можно идти в футболке")